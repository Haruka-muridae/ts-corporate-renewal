/*
 * Google Drive 上のフォルダ名の共通定義。
 *
 * 保存する側（音声録音アプリ）と読む側（音声文字起こしアプリ）で
 * 名前がずれると、同じ場所を指しているつもりで別の場所を見ることになる。
 * それを防ぐため、フォルダ名はこのファイル1か所だけで定義する。
 *
 * ------------------------------------------------------------------
 * ここに入れてよいもの / いけないもの
 * ------------------------------------------------------------------
 * 入れてよい … フォルダ「名」だけ
 * 入れてはいけない … フォルダID
 *
 * フォルダIDは利用者ごとに異なる。固定値として書くと、他の利用者の
 * ドライブでは存在しないIDを参照することになり、必ず失敗する。
 * IDは毎回「名前と親の関係」から解決すること。
 * ------------------------------------------------------------------
 *
 * 階層:
 *   マイドライブ
 *   └── TSAM AI
 *       ├── Voice Recorder     … 音声録音アプリの保存先
 *       ├── Audio Transcriber  … 音声文字起こしアプリのTXT保存先
 *       └── 名刺スキャナ        … 名刺スキャナ（このファイルは未使用）
 */

export const DRIVE_FOLDERS = Object.freeze({
  /* マイドライブ直下に置く最上位フォルダ。 */
  root: 'TSAM AI',

  /* TSAM AI 直下。音声録音アプリが録音（MP3）を保存する場所。 */
  voiceRecorder: 'Voice Recorder',

  /* TSAM AI 直下。音声文字起こしアプリが結果のTXTを保存する場所。 */
  audioTranscriber: 'Audio Transcriber',
});

/* 画面に出す「マイドライブ ＞ TSAM AI ＞ Voice Recorder」形式の表示。 */
export function formatFolderPath(...names) {
  return ['マイドライブ', ...names].join(' ＞ ');
}
