/*
 * ショート動画 台本メーカーの静的設定。**設定値を変えるのはこのファイルだけ。**
 *
 * ==================================================================
 * なぜ1本にまとめるか
 * ==================================================================
 * 領収書OCR・名刺OCR（../card-ocr/config.js）と同じく、定数を1本へ集約する。
 * 「この値はどこで決まっているのか」を毎回 grep で探さずに済ませるため。
 *
 * **秘密情報を置かない。** ここは公開URLから読める（静的ホスティング）。
 * APIキーは KeyStore（../../auth/keystore.js）だけが扱い、ここには現れない。
 * ==================================================================
 */

/* ================================================================
 * Gemini のモデルとエンドポイント
 * ================================================================
 *
 * 名刺OCR（../card-ocr/config.js §Gem)と同じ選定に揃える。
 * 主モデルが 404（廃止）のときだけ gemini.js がフォールバックへ切り替える。
 * 503（混雑）では切り替えない。混雑は待って直すものだからである。
 */
export const DEFAULT_MODEL = 'gemini-2.5-flash-lite';
export const FALLBACK_MODEL = 'gemini-3.5-flash-lite';

export const GEMINI_HOST = 'generativelanguage.googleapis.com';
export const GEMINI_ENDPOINT_BASE = `https://${GEMINI_HOST}/v1beta/models`;

/*
 * 出力の上限。台本は数百字なので大きくは要らないが、
 * **足りないと JSON が途中で切れて台本にならない**。
 * 60秒（最大7シーン）でも収まる余裕を見て 1024 にする。
 */
export const MAX_OUTPUT_TOKENS = 1024;

/* ================================================================
 * 動画の尺（秒）
 * ================================================================
 *
 * 30 / 60 の2択。ここを増やすと prompt.js のシーン数の指示も見直すこと
 * （尺だけ増やしてシーン数の指針が無いと、モデルの裁量で間延びする）。
 */
export const DURATIONS = Object.freeze([30, 60]);
export const DEFAULT_DURATION = 30;

/* テーマ入力の上限。長すぎる指示は要約されて意図から外れやすい。 */
export const THEME_MAX_LENGTH = 100;

/* ================================================================
 * ローカル補助サービス（音声・動画の生成）
 * ================================================================
 *
 * 音声（VOICEVOX）と動画（FFmpeg）は、利用者のPCで動くローカルの
 * 補助サービス（ai-video-app）が担う。ブラウザからこの原点へ台本を
 * POST して生成する。既定は 127.0.0.1:3000。
 *
 * **秘密情報ではない**（ローカルの原点であり、鍵も含まない）。
 * 別ポートで動かす場合はここを変える。
 */
export const COMPANION_BASE_URL = 'http://127.0.0.1:3000';

/* ================================================================
 * 台本の版
 * ================================================================
 *
 * prompt.js の指示を変えたら上げる。書き出した台本が「どの指示で
 * 作られたのか」を後から追えるようにするための値。
 */
export const APP_VERSION = 'short-script-1.0';
