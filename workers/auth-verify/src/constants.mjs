/*
 * セッション検証キャッシュの調整値。
 *
 * 仕様: docs/specs/auth-verify-cache-spec-v1.md
 */

/*
 * ------------------------------------------------------------------
 * 鮮度（TTL）を 30 分にした理由
 * ------------------------------------------------------------------
 * この値がそのまま「失効が反映されるまでの最大時間」になる。
 * ログアウト・パスワード変更・アカウント停止・契約切れのいずれも、
 * 最大でこの時間だけ旧セッションが通る（利用者了承済み。仕様 §4）。
 *
 * 短くすると再検証が増え、KV の書き込み（無料枠 1,000/日）を食う。
 * 15 分では 300 人規模で枠に対する余裕が薄く、60 分では失効の遅れが
 * 目立つ。30 分はその間で、実測（KV 書き込み 400〜800/日の見込み）に
 * 対しても余裕が残る。
 *
 * 書き込みが枠に迫った場合の手当ては、まずこの値を延ばすこと。
 * それでも足りなければ置き場を D1 へ移す（どちらも無料のまま）。
 * ------------------------------------------------------------------
 */
export const FRESH_MS = 30 * 60 * 1000;

/*
 * ------------------------------------------------------------------
 * 認証系 GAS が落ちているときの継続（grace）
 * ------------------------------------------------------------------
 * GAS へ届かない間、キャッシュ済みの検証結果をどこまで使い続けるか。
 *
 * notifier-gate は 72 時間だが、あちらは「通知が止まると困る」性質の
 * 判定であり、こちらは認証である。落ちている間ずっと入れてよいとは
 * しない。セッションの既定寿命（12 時間）と同じにして、grace が
 * セッション本来の寿命を超えないようにする。
 *
 * grace 中は失効が一切伝播しない。これは可用性のための妥協であり、
 * 上限を設けること自体が要件（仕様 §6）。
 * ------------------------------------------------------------------
 */
export const GRACE_MS = 12 * 60 * 60 * 1000;

/*
 * ------------------------------------------------------------------
 * 「無効」も短時間だけ覚える
 * ------------------------------------------------------------------
 * 覚えないと、無効なトークンを投げ続けるだけで GAS を叩き放題になる
 * （この Worker が増幅器になってしまう）。一方で長く覚えると、
 * ログインし直した直後に古い「無効」が効いてしまう。
 *
 * ただしトークンはログインのたびに新しく発行されるため、
 * 「同じトークンが無効から有効へ変わる」ことは起こらない。
 * 60 秒は総当たりを鈍らせるには十分で、実害が無い長さ。
 * ------------------------------------------------------------------
 */
export const NEGATIVE_MS = 60 * 1000;

/*
 * KV に置いておく期間。grace を過ぎた記録は使い道が無い。
 * KV の expirationTtl は 60 秒以上でなければならない。
 */
export const RECORD_TTL_SECONDS = Math.max(60, Math.floor(GRACE_MS / 1000));

/*
 * GAS への照会のタイムアウト。
 * 実測でコールドスタートに 35 秒かかることがあるため、
 * ブラウザ側の 30 秒（AUTH_CONFIG.requestTimeoutMs）より短くしない。
 * ここで切ると、利用者から見て「Worker のせいで失敗した」ことになる。
 */
export const GAS_TIMEOUT_MS = 30 * 1000;

/* セッショントークンの受け入れ形。gas-auth の verifySessionToken_ と同じ。 */
export const MAX_TOKEN_LENGTH = 256;
